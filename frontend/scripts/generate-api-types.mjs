import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';

const frontendRoot = process.cwd();
const repoRoot = path.resolve(frontendRoot, '..');
const schemaPath = path.join(repoRoot, 'docs/api/final_review_workspace_v1.schema.json');
const outputPath = path.join(frontendRoot, 'src/types/api.ts');

if (!fs.existsSync(schemaPath)) {
  throw new Error(`API schema is missing: ${schemaPath}`);
}

const schema = JSON.parse(fs.readFileSync(schemaPath, 'utf8'));
const definitions = schema.definitions || {};

const orderedNames = [
  'WorkspaceSummary',
  'Case',
  'MediaVersion',
  'TaskCollection',
  'Task',
  'TaskDecision',
  'Session',
  'SessionState',
  'Attribution',
  'EntityIndex',
  'Entity',
  'EntityPolicyAction',
  'BulkEntityPolicyAction',
  'EntityMergeCandidate',
  'EntityMergeEvent',
  'ManualPrivacyCategory',
  'Correction',
  'CorrectionPreview',
  'WorkingState',
  'MaterializationStatus',
  'MaterializationJob',
  'Checkpoint',
  'History',
  'AuditEvent',
  'FinalizationStatus',
  'VersionAlignmentAudit',
];

function refName(ref) {
  return ref.replace('#/definitions/', '');
}

function typeFromSchema(value) {
  if (!value || value === true) return 'unknown';
  if (value.$ref) return refName(value.$ref);
  if (value.anyOf) return value.anyOf.map((item) => typeFromSchema(item)).join(' | ');
  if (value.const !== undefined) return JSON.stringify(value.const);
  if (value.enum) return value.enum.map((item) => JSON.stringify(item)).join(' | ');
  if (Array.isArray(value.type)) {
    return value.type
      .map((item) => (item === 'null' ? 'null' : typeFromSchema({ ...value, type: item })))
      .join(' | ');
  }
  if (value.type === 'string') return 'string';
  if (value.type === 'null') return 'null';
  if (value.type === 'integer' || value.type === 'number') return 'number';
  if (value.type === 'boolean') return 'boolean';
  if (value.type === 'array') return `${typeFromSchema(value.items)}[]`;
  if (value.type === 'object') {
    if (value.properties) return inlineObject(value);
    if (value.additionalProperties && value.additionalProperties !== true) {
      return `Record<string, ${typeFromSchema(value.additionalProperties)}>`;
    }
    return 'Record<string, unknown>';
  }
  return 'unknown';
}

function inlineObject(value) {
  const required = new Set(value.required || []);
  const lines = ['{'];
  for (const [key, propertySchema] of Object.entries(value.properties || {})) {
    const optional = required.has(key) ? '' : '?';
    lines.push(`  ${JSON.stringify(key)}${optional}: ${typeFromSchema(propertySchema)};`);
  }
  if (value.additionalProperties === true) {
    lines.push('  [key: string]: unknown;');
  }
  lines.push('}');
  return lines.join('\n');
}

function emitDefinition(name, value) {
  const required = new Set(value.required || []);
  if (value.type === 'object' && value.properties) {
    const lines = [`export interface ${name} {`];
    for (const [key, propertySchema] of Object.entries(value.properties)) {
      const optional = required.has(key) ? '' : '?';
      lines.push(`  ${JSON.stringify(key)}${optional}: ${typeFromSchema(propertySchema)};`);
    }
    if (value.additionalProperties === true) {
      lines.push('  [key: string]: unknown;');
    }
    lines.push('}');
    return lines.join('\n');
  }
  return `export type ${name} = ${typeFromSchema(value)};`;
}

const body = orderedNames
  .map((name) => {
    if (!definitions[name]) {
      throw new Error(`Schema definition is missing: ${name}`);
    }
    return emitDefinition(name, definitions[name]);
  })
  .join('\n\n');

const output = `// Generated by frontend/scripts/generate-api-types.mjs from docs/api/final_review_workspace_v1.schema.json.
// Do not edit this file directly.

export const API_SCHEMA_VERSION = ${JSON.stringify(schema['x-api-schema-version'])};
export const API_PREFIX = ${JSON.stringify(schema['x-api-prefix'])};

${body}
`;

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, output, 'utf8');
